export function detectBankTheme(input: string): BankTheme {
  const normalized = (input || '').toLowerCase().trim();
  if (!normalized) return BANK_PRESETS[0];

  for (const preset of BANK_PRESETS) {
    if (preset.keywords.some((k) => normalized.includes(k.toLowerCase()))) {
      return preset;
    }
  }

  // Fallback to vibrant modern fintech preset
  return {
    id: 'custom',
    name: input || 'Özel Kart',
    keywords: [],
    gradient: 'from-[#1e1b4b] via-[#312e81] to-[#4338ca]',
    primaryColor: '#6366f1',
    secondaryColor: '#8b5cf6',
    textColor: '#ffffff',
    accentNeon: '#a855f7',
    chipColor: '#facc15',
    badgeBg: 'bg-indigo-500/20 text-indigo-300 border-indigo-500/40',
    logoText: (input || 'KART').toUpperCase().slice(0, 16),
  };
}
